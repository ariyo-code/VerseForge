"""Experimental deterministic Verse UI scaffold for annotated UI observations.

Only text, navigation/close buttons and widget lifecycle. This intentionally
isn't a UMG .uasset generator and must compile in the customer's actual UEFN.
"""
from __future__ import annotations

import re
from typing import Any

from .visual_reverse import plan_from_observations


def _message(value: str) -> str:
    """Escape a bounded text label rather than interpolating code from an image."""
    value = value[:110].replace('\\', '\\\\').replace('"', '\\"').replace('\r', '').replace('\n', ' ').replace('\t', ' ')
    return value or ' ' 


def generate_verse_ui(observations: dict[str, Any], *, device_name: str = 'vf_generated_ui_device') -> dict[str, Any]:
    plan = plan_from_observations(observations)
    if not re.fullmatch(r'[a-z][a-z0-9_]{2,55}', device_name):
        raise ValueError('Unsafe Verse device identifier')
    screens = plan['screens']
    screen_index = {screen['id']: i for i, screen in enumerate(screens)}
    # Do not fabricate actions from a screenshot; only explicit navigate/close
    # have deterministic matching event handlers. All other controls are visual.
    labels = []
    methods = []
    views = []
    commands = []
    for index, screen in enumerate(screens):
        slots = []
        for element in screen['elements']:
            ident = f's{index}_{element["id"]}'
            field = 'Label_' + ident
            label = element['text'] or element['kind'].capitalize()
            labels.append(f'    {field}<localizes>:message = "{_message(label)}"')
            kind = element['kind']
            action = element['action']
            target = element.get('target')
            if kind == 'button' and action == 'navigate' and target in screen_index:
                widget = 'button_loud'
                callback = 'Go_' + ident
                methods.extend([
                    f'    {callback}(Event:widget_message):void =',
                    f'        OpenForPlayer(Event.Player, {screen_index[target]})', ''])
            elif kind == 'button' and action == 'close':
                widget, callback = 'button_regular', 'OnExit'
            else:
                widget, callback = 'text_block', None
                if action not in {'display', 'unknown'}:
                    commands.append({'element': f'{screen["id"]}/{element["id"]}',
                                     'action': action, 'status': 'NOT IMPLEMENTED — REQUIRES AGENT GAMEPLAY CODE'})
            var = 'Widget_' + ident
            if widget == 'text_block':
                views.append(f'            {var}:text_block = text_block{{DefaultText := {field}}}')
            else:
                views.append(f'            {var}:{widget} = {widget}{{DefaultText := {field}}}')
                views.append(f'            set Listeners += array{{{var}.OnClick().Subscribe({callback})}}')
            # Use the center of the normalized bounding box for anchored Verse UI.
            b = element['bounds']
            x = max(0.0, min(1.0, b['x'] + b['w'] / 2))
            y = max(0.0, min(1.0, b['y'] + b['h'] / 2))
            slots += [
                '                    canvas_slot:',
                f'                        Anchors := anchors{{Minimum := vector2{{X := {x:.4f}, Y := {y:.4f}}}, Maximum := vector2{{X := {x:.4f}, Y := {y:.4f}}}}}',
                '                        Alignment := vector2{X := 0.5, Y := 0.5}',
                '                        SizeToContent := true',
                f'                        Widget := {var}',
            ]
        if not slots:
            labels.append(f'    Empty_{index}<localizes>:message = "No UI elements specified"')
            var = f'EmptyWidget_{index}'
            views.append(f'            {var}:text_block = text_block{{DefaultText := Empty_{index}}}')
            slots += [
                '                    canvas_slot:',
                '                        Anchors := anchors{Minimum := vector2{X := 0.5, Y := 0.5}, Maximum := vector2{X := 0.5, Y := 0.5}}',
                '                        Alignment := vector2{X := 0.5, Y := 0.5}',
                '                        SizeToContent := true',
                f'                        Widget := {var}',
            ]
        # Collect declarations per screen separately below to avoid scoping confusion.
        if index == 0:
            all_views = []
        all_views.append((index, views.copy(), slots))
        views.clear()
    code = [
        'using { /Fortnite.com/Devices }',
        'using { /Fortnite.com/UI }',
        'using { /Verse.org/Simulation }',
        'using { /UnrealEngine.com/Temporary/UI }',
        'using { /UnrealEngine.com/Temporary/SpatialMath }', '',
        '# Generated by VerseForge from host/user supplied visual observations.',
        '# EXPERIMENTAL — Verse compilation, UMG fidelity, runtime and multiplayer NOT TESTED.',
        '# Only explicitly described screen navigation and close behavior is connected.',
        f'{device_name} := class(creative_device):',
        '    @editable',
        '    OpenButton:button_device = button_device{}', '',
        '    var ActiveUI:[player]?canvas = map{}',
        '    var UIListeners:[player][]cancelable = map{}',
        '    var OpenSubscription:?cancelable = false',
        '    var LeaveSubscription:?cancelable = false', '',
    ]
    code += labels
    code += ['', '    OnBegin<override>()<suspends>:void =',
             '        set OpenSubscription = option{OpenButton.InteractedWithEvent.Subscribe(OnOpen)}',
             '        set LeaveSubscription = option{GetPlayspace().PlayerRemovedEvent().Subscribe(OnPlayerLeft)}', '',
             '    OnOpen(Who:agent):void =', '        if (P := player[Who]):',
             '            CloseForPlayer(P)', '            OpenForPlayer(P, 0)', '',
             '    OpenForPlayer(P:player, View:int):void =',
             '        CloseForPlayer(P)',
             '        if (PUI := GetPlayerUI[P]):',
             '            var Listeners:[]cancelable = array{}',
    ]
    for index, variables, slots in all_views:
        prefix = '            if' if index == 0 else '            else if'
        code.append(f'{prefix} (View = {index}):')
        code += [('    ' + line) for line in variables]
        code += ['                NewCanvas:canvas = canvas:', '                    Slots := array:']
        code += ['    ' + line for line in slots]
        code += ['                PUI.AddWidget(NewCanvas, player_ui_slot{InputMode := ui_input_mode.All})',
                 '                if (set ActiveUI[P] = option{NewCanvas}) {}',
                 '                if (set UIListeners[P] = Listeners) {}']
    code += ['', '    OnExit(Event:widget_message):void =',
             '        CloseForPlayer(Event.Player)', '']
    code += methods
    code += ['    CloseForPlayer(P:player):void =',
             '        if (Listeners := UIListeners[P]):',
             '            for (Listener : Listeners):',
             '                Listener.Cancel()',
             '        if (PUI := GetPlayerUI[P], Widget := ActiveUI[P]?):',
             '            PUI.RemoveWidget(Widget)',
             '        if (set ActiveUI[P] = false) {}',
             '        if (set UIListeners[P] = array{}) {}', '',
             '    OnPlayerLeft(P:player):void =',
             '        CloseForPlayer(P)', '',
             '    OnEnd<override>():void =',
             '        if (Subscription := OpenSubscription?):',
             '            Subscription.Cancel()',
             '        if (Subscription := LeaveSubscription?):',
             '            Subscription.Cancel()',
             '        for (P -> MaybeWidget : ActiveUI):',
             '            CloseForPlayer(P)', '']
    return {'schema': 'verseforge-verse-ui-scaffold-v1',
            'filename': f'{device_name}.verse', 'source': '\n'.join(code),
            'screens': len(screens), 'unimplemented_actions': commands,
            'source_status': 'GENERATED — COMPILATION NOT TESTED', 'uefn_compile': 'NOT TESTED',
            'umg_asset': 'NOT GENERATED', 'note': 'Only UI navigation/close is wired. Other gameplay interactions require explicit feature code.'}

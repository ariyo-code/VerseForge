"""Conservative static evidence report for agent-authored Verse artifacts.

This *cannot* compile Verse or prove gameplay. It checks path hygiene, local
syntax hints and an optional user-supplied acceptance contract without
confusing literal matches with behavioral evidence.
"""
from __future__ import annotations

import hashlib
import json
import re
import stat
from pathlib import Path
from typing import Any
from .gates import static_review

MAX_FILES = 150
MAX_BYTES = 30 * 1024 * 1024
MAX_SINGLE = 3 * 1024 * 1024
_NAME = re.compile(r"^[A-Za-z][A-Za-z0-9_ -]{0,119}$")
_FORBIDDEN_UNICODE = frozenset(["\u200b", "\u200c", "\u200d", "\ufeff", "\u202a", "\u202b", "\u202d", "\u202e", "\u202c", "\u2066", "\u2067", "\u2068", "\u2069"])


def _sources(root: Path) -> list[Path]:
    root = Path(root).expanduser().resolve(strict=True)
    if not root.is_dir():
        raise ValueError("Project source root must be a directory")
    out: list[Path] = []
    total = 0
    seen = set()
    for item in sorted(root.rglob("*")):
        mode = item.lstat().st_mode
        if stat.S_ISLNK(mode):
            raise ValueError(f"Symlink forbidden inside source root: {item}")
        if stat.S_ISDIR(mode):
            continue
        if not stat.S_ISREG(mode):
            raise ValueError("Nonregular input")
        if item.suffix.lower() != ".verse":
            continue
        rel = item.relative_to(root).as_posix()
        if rel.casefold() in seen:
            raise ValueError("Case-colliding Verse sources")
        seen.add(rel.casefold())
        size = item.stat().st_size
        total += size
        if size > MAX_SINGLE or total > MAX_BYTES or len(out) >= MAX_FILES:
            raise ValueError("Verse source input exceeds safety limits")
        out.append(item)
    if not out:
        raise ValueError("No .verse files found")
    return out


def _contract(contract: dict[str, Any] | None) -> list[dict[str, Any]]:
    if contract is None:
        return []
    if not isinstance(contract, dict) or contract.get("schema") != "verseforge-acceptance-v1":
        raise ValueError("Invalid acceptance contract")
    requirements = contract.get("requirements")
    if not isinstance(requirements, list) or not 1 <= len(requirements) <= 40:
        raise ValueError("Acceptance contract requires 1–40 requirements")
    names = set()
    out = []
    for item in requirements:
        if not isinstance(item, dict) or not isinstance(item.get("id"), str) or not _NAME.fullmatch(item["id"]):
            raise ValueError("Invalid acceptance requirement id")
        if item["id"] in names:
            raise ValueError("Duplicate acceptance requirement")
        names.add(item["id"])
        if item.get("validation") not in {"static-evidence", "manual-uefn", "multiplayer-uefn"}:
            raise ValueError("Unrecognized requirement validation level")
        phrase = item.get("contains")
        if phrase is not None and (not isinstance(phrase, str) or not 1 <= len(phrase) <= 160):
            raise ValueError("Invalid acceptance search text")
        if item["validation"] != "static-evidence" and phrase:
            # A literal string is not sufficient to prove real behavior.
            raise ValueError("Behavioral requirements cannot be satisfied by a text pattern")
        out.append(dict(item))
    return out


def review_sources(root: Path, contract: dict[str, Any] | None = None) -> dict[str, Any]:
    paths = _sources(root)
    base = Path(root).resolve(strict=True)
    requirements = _contract(contract)
    files = []
    merged = []
    warnings = []
    for path in paths:
        data = path.read_bytes()
        try:
            value = data.decode("utf-8")
        except UnicodeDecodeError as exc:
            raise ValueError(f"Verse file must be UTF-8: {path.name}") from exc
        issues = []
        if any(c in value for c in _FORBIDDEN_UNICODE):
            issues.append("Invisible or directional Unicode control found")
        if "TODO(API VERIFY)" in value:
            issues.append("Unverified Verse API marker present")
        if "# VerseForge engineering scaffold; NOT a functional game system." in value:
            issues.append("Template-only Verse scaffold: gameplay requirements NOT IMPLEMENTED")
        if "# Generated by VerseForge from host/user supplied visual observations." in value:
            issues.append("Experimental generated Verse UI: editor compilation and runtime NOT TESTED")
        if "\x00" in value:
            issues.append("NUL character present")
        static = static_review(path.name, value)
        if static.get("syntax_heuristics") == "FAIL":
            issues.append("Existing heuristic static-review returned a failure")
        for warning in static.get("warnings", []):
            issues.append(f"Heuristic: {warning}")
        rel = path.relative_to(base).as_posix()
        files.append({"path": rel, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest(),
                      "heuristic": static, "issues": issues})
        warnings += [f"{rel}: {issue}" for issue in issues]
        merged.append(value)
    full = "\n".join(merged)
    checks = []
    for item in requirements:
        if item["validation"] == "static-evidence":
            if "contains" in item:
                found = item["contains"] in full
                status = "TEXT FOUND — NOT BEHAVIORAL PROOF" if found else "MISSING TEXT"
            else:
                found = False
                status = "NOT TESTED — NO STATIC CONDITION"
        else:
            found = False
            status = "NOT TESTED — REQUIRES REAL UEFN EVIDENCE"
        checks.append({"id": item["id"], "validation": item["validation"], "status": status,
                       "static_match": bool(found)})
    return {
        "schema": "verseforge-static-evidence-v1", "source_count": len(files), "files": files,
        "warnings": warnings, "acceptance_checks": checks,
        "local_check": "PASS" if not warnings and not any(x["status"] == "MISSING TEXT" for x in checks) else "REVIEW REQUIRED",
        "uefn_compilation": "NOT TESTED", "gameplay": "NOT TESTED", "multiplayer": "NOT TESTED",
        "notice": "Literal matches and local heuristics do not prove Verse compilation, runtime correctness, or multiplayer behavior."
    }


def load_contract(path: Path) -> dict[str, Any]:
    path = Path(path)
    if path.stat().st_size > 128 * 1024:
        raise ValueError("Acceptance contract too large")
    return json.loads(path.read_text(encoding="utf-8"))
